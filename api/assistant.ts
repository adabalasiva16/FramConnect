export default async function handler(req: any, res: any) {
  if (req.method !== 'POST') {
    return res.status(405).json({ error: 'Method Not Allowed' });
  }

  try {
    const { message, language = 'en', userRole = 'customer' } = req.body || {};

    if (!message || typeof message !== 'string') {
      return res.status(400).json({ error: 'Message is required' });
    }

    const isTelugu = language === 'te' || /[\u0C00-\u0C7F]/.test(message);

    if (!aiClient) {
      const fallback = getSmartAgriculturalResponse(message, isTelugu, userRole);
      return res.status(200).json(fallback);
    }

    try {
      const systemPrompt = `You are the bilingual AI Assistant for "FarmConnect" (??????????????), an agricultural marketplace connecting farmers directly to consumers in Andhra Pradesh & Telangana.
User Role: ${userRole}.
Requested Language: ${isTelugu ? 'Telugu (??????)' : 'English'}.
Context available in app:
- Current crops available: Tomato (????? - ?34/kg), Rice (???? ????? - ?58/kg), Chilli (??????? ??? - ?185/kg), Onion (?????????? - ?28/kg), Potato (???????????? - ?26/kg), Banana (???? - ?45/kg), Groundnut (??????? - ?68/kg), Jaggery (?????? - ?75/kg).
- User query: "${message}".

Instructions:
1. Provide a warm, concise, and helpful answer in ${isTelugu ? 'simple, natural Telugu' : 'clear English'}.
2. Set action if user wants to navigate:
- NAVIGATE_MARKET_PRICES
- NAVIGATE_MARKETPLACE
- NAVIGATE_ADD_PRODUCT
- NAVIGATE_ORDERS
- NAVIGATE_FARMER_SALES
- SEARCH_CROP

Return pure JSON:
{
  "reply": "string",
  "action": { "type": "string" | null, "param": "string" | null },
  "suggestedFollowUps": ["string"]
}`;

      const response = await aiClient.models.generateContent({
        model: 'gemini-2.5-flash',
        contents: systemPrompt,
        config: {
          responseMimeType: 'application/json',
        },
      });
      const responseText = response.text || '{}';
      const parsedData = JSON.parse(responseText);
      return res.status(200).json(parsedData);
    } catch (apiError) {
      console.warn('Gemini generateContent timed out or errored, using smart fallback:', apiError);
      const fallback = getSmartAgriculturalResponse(message, isTelugu, userRole);
      return res.status(200).json(fallback);
    }
  } catch (error: any) {
    console.error('Error in /api/assistant:', error);
    const isTelugu = req.body?.language === 'te';
    return res.status(200).json(getSmartAgriculturalResponse(req.body?.message || '', isTelugu, req.body?.userRole || 'customer'));
  }
}
